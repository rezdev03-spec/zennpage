// Extracts authentic brand SVG paths from simple-icons into a typed TS module.
import { writeFileSync } from 'node:fs';
import * as si from 'simple-icons';

const pick = (...names) => names.map((n) => si[n]).find(Boolean);

const MAP = {
  tiktok: ['siTiktok'],
  whatsapp: ['siWhatsapp'],
  telegram: ['siTelegram'],
  python: ['siPython'],
  html5: ['siHtml5'],
  css3: ['siCss3', 'siCss'],
  javascript: ['siJavascript'],
  github: ['siGithub'],
  git: ['siGit'],
  nodedotjs: ['siNodedotjs'],
  react: ['siReact'],
  vercel: ['siVercel'],
};

const out = {};
for (const [key, names] of Object.entries(MAP)) {
  const icon = pick(...names);
  if (!icon) throw new Error(`Missing icon for ${key}: tried ${names.join(', ')}`);
  out[key] = { title: icon.title, hex: icon.hex, path: icon.path };
}

const body = `/**
 * Authentic brand marks — path data sourced from the Simple Icons project
 * (https://simpleicons.org, CC0-1.0). Generated by scripts/gen-icons.mjs.
 * Brand trademarks belong to their respective owners.
 */
export interface BrandGlyph {
  title: string;
  hex: string;
  path: string;
}

export const BRAND_GLYPHS: Record<string, BrandGlyph> = ${JSON.stringify(out, null, 2)} as const;
`;

writeFileSync('src/lib/brands.ts', body);
console.log('wrote src/lib/brands.ts with:', Object.keys(out).join(', '));
console.log('css3 resolved title:', out.css3.title, '| react hex:', out.react.hex);
